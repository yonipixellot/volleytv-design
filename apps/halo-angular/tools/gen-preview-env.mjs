/* Writes src/preview-gate/env.generated.ts from the build environment.
   Runs from the `prebuild` npm script, so it fires on every `npm run build`
   (local and on Vercel) before ng compiles.

   Angular offers no NEXT_PUBLIC_*-style inlining, so this is how the preview
   gate's Supabase credentials reach the bundle. NEXT_PUBLIC_-prefixed names
   are read first so the env vars already configured on the Vercel project
   (carried over from the Next.js design-preview deploy) work untouched.

   REQUIRE_AUTH is what keeps the GitHub Pages deploy working. That site is
   private-repo Pages, so GitHub's own org login already gates it (HANDOFF.md
   §3) and it has no Supabase vars. Arming the gate there would just show a
   "not configured" screen and never boot the app. So the gate arms ONLY on
   Vercel, which is the deploy that is actually public. Vercel sets VERCEL=1
   on every build; nothing else does.

   On Vercel the gate fails CLOSED: if the Supabase vars are missing or
   misspelled, the build still succeeds but the app refuses to boot and shows
   the "not configured" screen, rather than silently publishing the design. */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const url = process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL || '';
const anonKey =
  process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || process.env.SUPABASE_ANON_KEY || '';
const requireAuth = Boolean(process.env.VERCEL);

/* JSON.stringify, not raw interpolation — a stray quote or backslash in an
   env var would otherwise produce a file that doesn't parse. */
const out = `/* AUTO-GENERATED by tools/gen-preview-env.mjs — do not edit by hand. */
export const SUPABASE_URL = ${JSON.stringify(url)};
export const SUPABASE_ANON_KEY = ${JSON.stringify(anonKey)};
export const REQUIRE_AUTH = ${JSON.stringify(requireAuth)};
`;

const target = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'preview-gate',
  'env.generated.ts',
);
writeFileSync(target, out, 'utf8');

if (!requireAuth) {
  console.log('[preview-gate] Not a Vercel build — gate disabled (GitHub Pages is gated by GitHub org login).');
} else if (url && anonKey) {
  console.log('[preview-gate] Vercel build — gate armed, Supabase credentials baked in.');
} else {
  console.log(
    '[preview-gate] ERROR: Vercel build with no Supabase env vars — the app will refuse to boot. ' +
      'Set NEXT_PUBLIC_SUPABASE_URL and NEXT_PUBLIC_SUPABASE_ANON_KEY on the project.',
  );
}
